import pandas as pd
df = pd.read_csv("data/raw/online_retail_II.csv", encoding="latin1")
df["InvoiceDate"] = pd.to_datetime(df["InvoiceDate"], format="mixed")
df = df.rename(columns={"Customer ID": "CustomerID", "UnitPrice": "Price"})
print("\n==============================================")
print("Shape:", df.shape)
print("\nMissing values per column:\n", df.isna().sum())
print("\nMissing Customer ID %:", round(df.CustomerID.isna().mean() * 100, 1))
print("\nDuplicate rows:", df.duplicated().sum())
print("\nCancelled invoices:", df.Invoice.astype(str).str.startswith("C").sum())
print("\nNegative or zero quantity rows:", (df.Quantity <= 0).sum())
print("Zero or negative price rows:", (df.Price <= 0).sum())
print("\nTop 5 countries by rows:\n", df.Country.value_counts().head(5))
print("\nQuantity summary:\n", df.Quantity.describe())
print("\nPrice summary:\n", df.Price.describe())
df["Month"] = df.InvoiceDate.dt.to_period("M")
print("\nRows per month:\n", df.groupby("Month").size())
print("==============================================\n")
